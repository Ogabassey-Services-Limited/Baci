// Generates the baked first-slide art AVIF used by the ogabassey mobile loading
// shell (apps/web/src/config/ogabassey-shell-banner-inline.ts).
//
// Why baked art? The PPR loading shell needs a LARGE, first-flush, inline LCP
// candidate (full-width <img>) — that is what makes the hero the Largest
// Contentful Paint. Rendering the live hero as a small contained image instead
// demoted LCP to the navbar logo. This composites the first hero slide
// background + phone art that already ships inline into one full-width image so
// the shell paints a big, fast LCP element with zero network cost, then the live
// carousel swaps in. Text and CTA remain HTML so storefront theme variables own
// the merchant-colored chrome.
//
// The phone art is decoded from the existing inline hero asset so this stays
// reproducible from repo sources.
//
// Run:  node scripts/generate-ogabassey-shell-banner.mjs
// Deps: sharp (already present via Next image optimization).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const here = dirname(fileURLToPath(import.meta.url));
const WEB_SRC = resolve(here, '../apps/web/src');

const INLINE_ASSET = resolve(WEB_SRC, 'config/ogabassey-hero-inline-assets.ts');
const OUT = resolve(WEB_SRC, 'config/ogabassey-shell-banner-inline.ts');

const W = 960;
const H = 540;
const BG = '#F5F5F7';

function decodePhoneArt() {
  const ts = readFileSync(INLINE_ASSET, 'utf8');
  const arr = ts.match(/\[([\s\S]*?)\]\.join\(/);
  if (!arr) throw new Error('Could not find inline hero base64 array');
  const b64 = arr[1]
    .split(',')
    .map((s) => s.trim().replace(/^['"]|['"]$/g, ''))
    .filter(Boolean)
    .join('');
  return Buffer.from(b64, 'base64');
}

function emitConfig(avif) {
  const b64 = avif.toString('base64');
  const lines = (b64.match(/.{1,96}/g) ?? []).map((l) => `  '${l}',`).join('\n');
  const body = `// AUTO-GENERATED by scripts/generate-ogabassey-shell-banner.mjs — do not edit by hand.
// Full-width baked first-slide art (light bg + phone) used as the ogabassey
// mobile loading shell hero. Inlined so it paints a large, first-flush LCP
// candidate with zero network cost; HTML owns themed copy/CTA chrome.
const OGABASSEY_SHELL_BANNER_INLINE_BASE64 = [
${lines}
].join('');

export const OGABASSEY_SHELL_BANNER_INLINE_WIDTH = ${W};
export const OGABASSEY_SHELL_BANNER_INLINE_HEIGHT = ${H};
export const OGABASSEY_SHELL_BANNER_INLINE_SRC = \`data:image/avif;base64,\${OGABASSEY_SHELL_BANNER_INLINE_BASE64}\`;
`;
  writeFileSync(OUT, body);
}

const phoneArt = decodePhoneArt();
const cropped = await sharp(phoneArt)
  .trim({ threshold: 10 })
  .toBuffer({ resolveWithObject: true });
const targetH = Math.round(H * 0.78);
const scale = targetH / cropped.info.height;
const targetW = Math.round(cropped.info.width * scale);
const phone = await sharp(cropped.data).resize(targetW, targetH).toBuffer();

const composed = await sharp({
  create: { width: W, height: H, channels: 3, background: BG },
})
  .composite([
    { input: phone, left: W - targetW - 48, top: Math.round((H - targetH) / 2) },
  ])
  .png()
  .toBuffer();

const avif = await sharp(composed).avif({ quality: 42, effort: 7 }).toBuffer();
emitConfig(avif);
console.log(`Wrote ${OUT} (${avif.length} bytes AVIF)`);
